package user

import (
	"api/internal/httpx"
	"context"
	"errors"
	"log"
	"net/http"
	"strconv"
)

type Repository interface {
	List(context.Context) ([]User, error)
	Create(context.Context, CreateUserParams) (User, error)
	GetByTelegramID(context.Context, int64) (User, error)
}

// List returns all users, including users without spendings.
// @Summary List family members
// @Tags Admin Users
// @Produce json
// @Success 200 {array} User
// @Failure 500 {object} httpx.ErrorResponse
// @Router /admin/users [get]
func (h *Handler) List(w http.ResponseWriter, r *http.Request) {
	users, err := h.users.List(r.Context())
	if err != nil {
		log.Printf("list users: %v", err)
		httpx.WriteError(w, errInternal)
		return
	}
	httpx.WriteJSON(w, http.StatusOK, users)
}

type Handler struct {
	users Repository
}

func NewHandler(users Repository) *Handler {
	return &Handler{users: users}
}

// Create creates a user linked to a Telegram account.
// @Summary Create user
// @Description telegram_user_id is required and must be positive. username and name are optional (up to 64 and 128 characters). The internal user ID is generated by the server.
// @Tags Users
// @Accept json
// @Produce json
// @Param request body CreateUserParams true "User data"
// @Success 201 {object} User "User created"
// @Failure 400 {object} httpx.ErrorResponse "Invalid JSON or validation error"
// @Failure 409 {object} httpx.ErrorResponse "User with this telegram_user_id already exists"
// @Failure 500 {object} httpx.ErrorResponse "Internal server error"
// @Router /users [post]
func (h *Handler) Create(w http.ResponseWriter, r *http.Request) {
	var params CreateUserParams
	if err := httpx.DecodeJSON(r, &params); err != nil {
		httpx.WriteError(w, errInvalidJSON)
		return
	}
	if err := httpx.Validate(params); err != nil {
		httpx.WriteValidationError(w, err)
		return
	}

	result, err := h.users.Create(r.Context(), params)
	if errors.Is(err, ErrAlreadyExists) {
		httpx.WriteError(w, errUserAlreadyExists)
		return
	}
	if err != nil {
		log.Printf("create user: %v", err)
		httpx.WriteError(w, errInternal)
		return
	}
	httpx.WriteJSON(w, http.StatusCreated, result)
}

// GetByTelegramID finds the internal user linked to a Telegram account.
// @Summary Find user by Telegram ID
// @Tags Users
// @Produce json
// @Param telegram_user_id query int true "Telegram user ID" minimum(1)
// @Success 200 {object} User
// @Failure 400 {object} httpx.ErrorResponse
// @Failure 404 {object} httpx.ErrorResponse
// @Failure 500 {object} httpx.ErrorResponse
// @Router /users [get]
func (h *Handler) GetByTelegramID(w http.ResponseWriter, r *http.Request) {
	telegramID, err := strconv.ParseInt(r.URL.Query().Get("telegram_user_id"), 10, 64)
	if err != nil {
		httpx.WriteError(w, errInvalidTelegramID)
		return
	}
	if err := httpx.Validate(TelegramIDParams{TelegramUserID: telegramID}); err != nil {
		httpx.WriteValidationError(w, err)
		return
	}
	result, err := h.users.GetByTelegramID(r.Context(), telegramID)
	if errors.Is(err, ErrNotFound) {
		httpx.WriteError(w, errNotFound)
		return
	}
	if err != nil {
		log.Printf("get user by Telegram ID: %v", err)
		httpx.WriteError(w, errInternal)
		return
	}
	httpx.WriteJSON(w, http.StatusOK, result)
}
